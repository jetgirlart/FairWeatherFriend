#include "display.h"

void drawKitsuneSprite(const uint8_t *bitmap, int x, int y,
                       uint8_t earOffset, bool crouching) {
  constexpr uint8_t width = KITSUNE_WIDTH * 2;
  constexpr uint8_t height = KITSUNE_HEIGHT * 2;
  constexpr uint8_t stride = width / 8;
  uint8_t scaled[stride * height] = {};
  // Expand the PROGMEM art with nearest-neighbor pixels. Only the left ear
  // tip moves during its existing 1/2-pixel twitch; no shape is reconstructed.
  for (uint8_t sy = 0; sy < height; ++sy) {
    // Shorten the torso by three physical rows for the existing storm crouch.
    // drawPet's +3 y offset keeps the feet on the same baseline.
    if (crouching && (sy == 35 || sy == 37 || sy == 39)) continue;
    uint8_t dy = sy - (crouching ? (sy > 35) + (sy > 37) + (sy > 39) : 0);
    for (uint8_t sx = 0; sx < width; ++sx) {
      uint8_t sourceX = sx / 2;
      uint8_t bits = pgm_read_byte(bitmap + (sy / 2) * 3 + sourceX / 8);
      if (!(bits & (0x80 >> (sourceX % 8)))) continue;
      uint8_t dx = sx + (sy < 12 && sx < 18 ? earOffset : 0);
      if (dx < width) scaled[dy * stride + dx / 8] |= 0x80 >> (dx % 8);
    }
  }
  // RAM-bitmap overload: compose into the existing framebuffer only.
  display.drawBitmap(x, y, scaled, width, height - (crouching ? 3 : 0), SH110X_WHITE);
}

